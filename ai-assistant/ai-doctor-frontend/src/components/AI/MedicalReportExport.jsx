// src/components/AI/MedicalReportExport.jsx

import { useRef } from 'react';

const MedicalReportExport = ({ patient, prediction, comparison, validation }) => {

  const handlePrint = () => {
    const reportContent = `
      ╔════════════════════════════════════════╗
      ║       AI DOCTOR ASSISTANT REPORT       ║
      ╚════════════════════════════════════════╝

      Patient ID: ${patient?.id || 'N/A'}
      Date: ${new Date().toLocaleDateString()}
      Time: ${new Date().toLocaleTimeString()}

      ─────────────────────────────────────────
      SYMPTOMS REPORTED:
      ${patient?.symptoms?.map(s => `• ${s.replace(/_/g, ' ')}`).join('\n') || 'None'}

      ─────────────────────────────────────────
      AI PREDICTION:
      Disease: ${prediction?.predicted_disease || 'N/A'}
      Confidence: ${prediction?.confidence || 0}%
      Specialist: ${prediction?.specialist || 'N/A'}

      Recommended Tests:
      ${prediction?.recommended_tests?.map(t => `• ${t}`).join('\n') || 'None'}

      Suggested Medicines:
      ${prediction?.suggested_medicines?.map(m => `• ${m}`).join('\n') || 'None'}

      ─────────────────────────────────────────
      DOCTOR DIAGNOSIS:
      ${comparison?.doctor_diagnosis || 'Not entered'}

      Match with AI: ${comparison?.match_status || 'N/A'}

      ─────────────────────────────────────────
      LAB VALIDATION:
      ${validation?.lab_confirmed_disease
        ? `Confirmed: ${validation.lab_confirmed_disease}
      AI Correct: ${validation.ai_correct ? 'Yes' : 'No'}
      Doctor Correct: ${validation.doctor_correct ? 'Yes' : 'No'}`
        : 'Pending lab results'}

      ─────────────────────────────────────────
      Generated by AI Doctor Assistant v1.0
    `;

    const printWindow = window.open('', '_blank');
    printWindow.document.write(`
      <html>
        <head>
          <title>Medical Report - ${patient?.id}</title>
          <style>
            body { font-family: monospace; padding: 40px; }
            pre { white-space: pre-wrap; }
          </style>
        </head>
        <body>
          <pre>${reportContent}</pre>
        </body>
      </html>
    `);
    printWindow.document.close();
    printWindow.print();
  };

  const handleDownloadJSON = () => {
    const reportData = {
      generated_at: new Date().toISOString(),
      patient, prediction, comparison, validation
    };

    const blob = new Blob(
      [JSON.stringify(reportData, null, 2)],
      { type: 'application/json' }
    );
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `medical_report_${patient?.id}_${Date.now()}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex gap-2">
      <button onClick={handlePrint} className="btn-ghost text-sm">
        🖨️ Print Report
      </button>
      <button onClick={handleDownloadJSON} className="btn-ghost text-sm">
        📥 Download JSON
      </button>
    </div>
  );
};

export default MedicalReportExport;